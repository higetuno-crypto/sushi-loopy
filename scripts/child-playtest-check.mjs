import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { setTimeout as wait } from 'node:timers/promises';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/higes/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const results = [];
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:5178');
  const state = () => page.evaluate(async () => (await import('/src/game/state/store.ts')).useGameStore.getState().totalClicks);
  const button = page.locator('.sushi-button');
  await button.tap();
  assert.equal(await state(), 1);
  results.push('touch tap counts once');
  const belt = page.locator('.conveyor-strip > div');
  assert.equal(await belt.evaluate(e => getComputedStyle(e).animationName), 'none');
  await page.clock.install();
  const box = await button.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.clock.runFor(760);
  assert.equal(await state(), 5);
  assert.ok(await page.locator('.sushi-drop').count() > 0);
  await page.mouse.up();
  await page.clock.runFor(1000);
  assert.equal(await state(), 5);
  results.push('hold: immediate + 250ms repeats, release stops, no duplicate click');
  await button.focus();
  await page.keyboard.press('Enter');
  assert.equal(await state(), 6);
  results.push('keyboard activation retained');
  await page.mouse.down();
  const beforeBlur = await state();
  await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  await page.clock.runFor(1000);
  assert.equal(await state(), beforeBlur);
  await page.mouse.up();
  results.push('blur cancels hold');
  await page.evaluate(async () => (await import('/src/game/state/store.ts')).useGameStore.setState({ sushi: 1000 }));
  await page.getByRole('button', { name: '職人さんを購入', exact: true }).tap();
  assert.equal(await page.locator('.purchase-pop').count(), 1);
  assert.match(await page.locator('.sushi-box-facilities').innerText(), /職人さん/);
  await page.getByRole('button', { name: '回転寿司オープンを購入', exact: true }).tap();
  assert.equal(await belt.evaluate(e => getComputedStyle(e).animationName), 'conveyor');
  const transform = await belt.evaluate(e => getComputedStyle(e).transform);
  await page.clock.runFor(500);
  // CSS timelines use real rendering time independently of the mocked JS clock.
  await wait(150);
  assert.notEqual(await belt.evaluate(e => getComputedStyle(e).transform), transform);
  results.push('purchase feedback and owned facilities; conveyor starts only after opening');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await belt.evaluate(e => getComputedStyle(e).animationName), 'none');
  assert.match(await page.locator('.sushi-box-heading').innerText(), /お皿がまわりはじめた/);
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  assert.equal(await button.evaluate(e => getComputedStyle(e).touchAction), 'none');
  assert.equal(await page.locator('.game-screen').evaluate(e => getComputedStyle(e).webkitUserSelect), 'none');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.clock.resume();
  await wait(1800);
  await page.screenshot({ path: 'artifacts/child-playtest-mobile.png' });
  await page.locator('.content-panel').scrollIntoViewIfNeeded();
  const dock = page.locator('.mobile-tap-dock button');
  await dock.waitFor({ state: 'visible' });
  const count = await state();
  await dock.tap();
  assert.equal(await state(), count + 1);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  results.push('mobile dock, selection protection, reduced motion, no overflow or runtime errors');
  await writeFile('artifacts/child-playtest-results.json', JSON.stringify({ status: 'PASS', browser: 'Edge mobile emulation; physical iPhone not tested', results, initialBeltTransform: transform }, null, 2));
  console.log(results);
} finally { await browser.close(); }
